"""
Prompts for the two Gemini calls: transcription, then analysis.

The company description lives in Grandstream Settings (company_context) so it can be
edited without a deploy. DEFAULT_COMPANY_CONTEXT is only used when that field is empty.
"""

DEFAULT_COMPANY_CONTEXT = """\
أماكن مجموعة شركات عقارية في السعودية:
1. مجموعة أماكن الدولية: مزادات عقارية، تسويق عقارات، تسويق مشاريع، إدارة أملاك.
   العملاء: مستثمرين، أو مستهلكين عايزين بيت أو شقة للسكن، أو ملاك عايزين يبيعوا عقار من خلال مزاد.
   في المزادات من عملائنا جهات زي مركز الإسناد والتصفية.
2. أماكن للتقييم: تقييم عقارات وتقييم مشاريع. العملاء: البنوك والأفراد والجهات الحكومية.
المسوقين تابعين للمجموعة، لكن ممكن يكلموا عملاء التقييم كمان.
"""

TRANSCRIBE = """\
اكتب المكالمة دي حرفياً باللهجة اللي اتقالت بيها (غالباً سعودي أو مصري).
- كل سطر يبدأ بـ "المسوق:" أو "العميل:".
- المسوق هو موظف شركة أماكن.
- ما تلخصش، وما تصححش الكلام، وما تترجمش.
- أي جزء مش واضح اكتب مكانه [غير واضح].
- لو التسجيل فاضي أو مفيش كلام، اكتب: [لا يوجد كلام]
اكتب النص بس، من غير أي مقدمة.
"""

OUTGOING_CRITERIA = [
    ("الافتتاحية", "عرّف بنفسه وبالشركة وسبب الاتصال"),
    ("فهم الاحتياج", "اتأكد إن العميل لسه مهتم، وسأل عن نوع الطلب والميزانية والتوقيت"),
    ("العرض", "عرض الخدمة أو العقار بشكل مناسب للاحتياج"),
    ("الاعتراضات", "رد على اعتراضات العميل بهدوء وإقناع"),
    ("الإغلاق", "اتفق على خطوة جاية محددة بتاريخ (معاينة، اجتماع، تسجيل في مزاد، إرسال عرض)"),
    ("الأسلوب", "استمع كويس، وما قاطعش العميل، وكان محترف"),
]

INCOMING_CRITERIA = [
    ("الافتتاحية", "رحّب بالعميل وعرّف بنفسه"),
    ("فهم الاحتياج", "فهم طلب العميل أو مشكلته صح"),
    ("العرض", "المعلومة أو الحل اللي قدمه صح وواضح"),
    ("الاعتراضات", "تعامل كويس مع العميل لو كان متضايق أو معترض"),
    ("الإغلاق", "العميل خرج عارف هيحصل إيه بعد كده"),
    ("الأسلوب", "استمع كويس، وما قاطعش العميل، وكان محترف"),
]

OUTGOING_SUCCESS = """\
المكالمة صادرة: المسوق هو اللي اتصل بعميل سجل اهتمامه في حملة.
المكالمة ناجحة لو المسوق عمل التلاتة دول:
1. اتأكد إن العميل لسه مهتم.
2. فهم هو عايز إيه (شراء، استثمار، بيع في مزاد، تقييم) وميزانيته وتوقيته.
3. اتفق معاه على خطوة جاية محددة بتاريخ.
لو العميل غير مهتم: المكالمة ما تتحسبش فشل على المسوق، بشرط إن العميل فعلاً مش مهتم،
وإن المسوق سأله عن السبب بأدب. لازم تتأكد إن المسوق ما خسرش العميل بأسلوبه.
"""

INCOMING_SUCCESS = """\
المكالمة واردة: العميل هو اللي اتصل بالشركة.
المكالمة ناجحة لو العميل وصل للي هو عايزه، سواء طلب أو حل مشكلة.
"""


def criteria_for(call_type):
    return OUTGOING_CRITERIA if call_type == "Outgoing" else INCOMING_CRITERIA


def system(company_context, call_type):
    criteria = "\n".join(
        f"{i}. {name}: {desc}" for i, (name, desc) in enumerate(criteria_for(call_type), 1)
    )
    success = OUTGOING_SUCCESS if call_type == "Outgoing" else INCOMING_SUCCESS
    return f"""\
إنت مشرف جودة مكالمات في شركة أماكن، وبتقيّم مكالمة واحدة من نصها المكتوب.

## عن الشركة
{(company_context or "").strip() or DEFAULT_COMPANY_CONTEXT}

## معيار النجاح
{success}
## معايير تقييم المسوق (كل معيار من 1 إلى 5)
{criteria}

## قواعد
- قيّم من الكلام اللي في النص بس. ما تفترضش حاجة ما اتقالتش.
- كل درجة لازم يكون معاها سبب واقتباس قصير من المكالمة.
- لو معيار ما ينطبقش على المكالمة (مثلاً مفيش اعتراضات)، اديله 3 واكتب إنه لا ينطبق.
- الملاحظات التدريبية موجهة للمسوق نفسه عشان يطور من نفسه، بأسلوب محترم ومحدد:
  "كان ممكن تسأل العميل عن ميزانيته قبل ما تعرض السعر"، مش "أداء ضعيف".
- اكتب كل الإجابات بالعربي.
"""


def analysis_input(call_type, transcript, reference=None, duration=None):
    direction = "صادرة (المسوق اتصل)" if call_type == "Outgoing" else "واردة (العميل اتصل)"
    lines = [f"نوع المكالمة: {direction}"]
    if duration:
        lines.append(f"مدة المكالمة: {duration} ثانية")
    if reference:
        lines.append(f"مرتبطة بـ: {reference}")
    lines.append("")
    lines.append("## نص المكالمة")
    lines.append(transcript)
    return "\n".join(lines)
